#!/usr/bin/env python3
"""Appendix F: per-trial result tables, generated from docs/report/results/*.csv and
data/robot/results.json. Run after analyze_results.py and robot_replay.py report."""
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, 'docs', 'report', 'results')
OUT = os.path.join(ROOT, 'docs', 'report', 'appendix', 'F_per_trial.md')
COND = {'condA': 'A', 'condB': 'B', 'condC': 'C', 'marker_on': 'A (band check)'}
f = lambda v, n=1: '–' if v in ('', 'nan', None) else f'{float(v):.{n}f}'
yn = lambda v: 'yes' if v == 'True' else 'no'


def table(header, rows):
    return '\n'.join(['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)] +
                     ['| ' + ' | '.join(map(str, r)) + ' |' for r in rows]) + '\n'


paired = list(csv.DictReader(open(os.path.join(RES, 'paired_trials.csv'))))
mmr = list(csv.DictReader(open(os.path.join(RES, 'mmr_trials.csv'))))
robot = json.load(open(os.path.join(ROOT, 'data', 'robot', 'results.json')))
key = lambda r: (r['task'], r['group'] if 'group' in r else r['cond'], int(r['trial']))
out = ['# Appendix F. Per-trial results\n',
       'Generated by `scripts/make_appendix_tables.py` from the analysis outputs. Errors in mm '
       '(RealSense against Vicon). Captured: no detection gap above 0.5 s between leaving and '
       'returning to START, and on the correct hand. Max gap in s.\n']

out.append('\n## F.1 Session 2, corner registration (accuracy, Section 3.3)\n')
rows = sorted((r for r in paired if r['session'] == 'S2' and r['registration'] == 'corner'), key=key)
out.append(table(['Task', 'Cond.', 'Trial', 'RMSE', 'Median', 'p95', 'Hold', 'Transit', 'Pick-up', 'At block',
                  'Max rot. (°)', 'Captured', 'Max gap'],
                 [[r['task'][-1], COND[r['group']], r['trial'], f(r['rmse']), f(r['median']), f(r['p95']),
                   f(r['med_hold']), f(r['med_transit']), f(r['med_pick']), f(r['med_place']), f(r['max_rot'], 0),
                   yn(r['captured']), f(r['max_gap'], 2)] for r in rows]))

out.append('\n## F.2 Session 1, wrist-based registration (Sections 3.3.4 and 3.4)\n')
rows = sorted((r for r in paired if r['session'] == 'S1'), key=key)
out.append(table(['Task', 'Cond.', 'Trial', 'RMSE', 'Median', 'p95', 'Calib. take', 'Captured', 'Max gap',
                  'Frames with detection (%)'],
                 [[r['task'][-1], COND[r['group']], r['trial'], f(r['rmse']), f(r['median']), f(r['p95']), r['calib'],
                   yn(r['captured']), f(r['max_gap'], 2), f(r['det_pct'])] for r in rows]))

out.append('\n## F.3 RealSense-only campaign, MMR (robustness, Section 3.4)\n')
rows = sorted(mmr, key=key)
out.append(table(['Task', 'Cond.', 'Trial', 'Captured', 'Wrong hand', 'Max gap', 'Predicted samples (%)',
                  'Frames with detection (%)', 'Tracker rate (Hz)'],
                 [[r['task'][-1], COND[r['cond']], r['trial'], yn(r['captured']), yn(r['wrong_hand']),
                   f(r['max_gap'], 2), f(r['pred_pct'], 2), f(r['det_pct']), f(r['proc_hz'])] for r in rows]))

out.append('\n## F.4 Robot replay (Section 3.6)\n\nPredicted error: horizontal distance from the '
           'commanded insertion point to the touched hole centre. Note: the operator\'s observation.\n\n')
rows = sorted(robot, key=lambda o: (o['offset_mode'], o['run']))
out.append(table(['Offset', 'Run', 'Trial', 'Source', 'Predicted error (mm)', 'Outcome', 'Peak force (N)', 'Note'],
                 [['other trials' if o['offset_mode'] == 'mean' else 'same trial', o['run'], o['trial'],
                   o['source'], f'{(o["pred_err_mm"][0] ** 2 + o["pred_err_mm"][1] ** 2) ** 0.5:.1f}', o['outcome'],
                   f(o['peak_force_N']), o.get('note', '').replace('|', '/')] for o in rows]))

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w').write('\n'.join(out))
print('saved', OUT)
